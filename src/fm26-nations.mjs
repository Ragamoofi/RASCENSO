export function fmNationToCode(id){
 if(id==null||id==='')return null;
 const raw=String(id).trim();
 if(!/^\d+$/.test(raw))return null;
 return FM_NATIONS[Number(raw)]||null;
}
export function fmNationName(id){
 const cc=fmNationToCode(id);
 if(!cc)return 'Nacionalidad sin identificar';
 if(SPECIAL_NAMES[cc])return SPECIAL_NAMES[cc];
 try{return DISPLAY.of(cc)||'Nacionalidad sin identificar'}catch{return 'Nacionalidad sin identificar'}
}
